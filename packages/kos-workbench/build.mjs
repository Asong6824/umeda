import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.dirname(fileURLToPath(import.meta.url));
const result = await build({ entryPoints: [path.join(root, 'src/main.tsx')], bundle: true, outfile: path.join(root, 'dist/workbench.js'), format: 'iife', target: 'es2022', platform: 'browser', minify: true, write: false, metafile: true,
  define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'inline' });
const js = result.outputFiles.find(file => file.path.endsWith('.js')).text;
const readers = await build({ entryPoints: [path.join(root, 'src/reader/runtime.ts')], bundle: true, format: 'iife', globalName: 'UmedaReaders', target: 'es2022', platform: 'browser', minify: true, write: false, metafile: true, legalComments: 'inline' });
const readerJs = readers.outputFiles[0].text;
const packages = new Map();
for (const input of Object.keys({ ...result.metafile.inputs, ...readers.metafile.inputs })) {
  if (!input.includes('node_modules/')) continue;
  let directory = path.dirname(path.resolve(input));
  while (directory !== path.dirname(directory)) {
    const manifest = await fs.readFile(path.join(directory, 'package.json'), 'utf8').then(JSON.parse).catch(() => null);
    if (manifest?.name) { packages.set(`${manifest.name}@${manifest.version}`, { manifest, directory }); break; }
    directory = path.dirname(directory);
  }
}
let notices = `KOS framework (MIT)\n${await fs.readFile(path.join(root, 'LICENSE.kos-framework'), 'utf8')}\n`;
for (const [identity, { manifest, directory }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  notices += `\n\n${identity} — ${manifest.license ?? 'See license below'}\n`;
  for (const name of await fs.readdir(directory)) if (/^(license|copying|notice)(\.|$)/i.test(name) && (await fs.stat(path.join(directory, name))).isFile()) notices += await fs.readFile(path.join(directory, name), 'utf8') + '\n';
}

const css = (result.outputFiles.find(file => file.path.endsWith('.css'))?.text ?? '') + '\n' + await fs.readFile(path.join(root, 'src/ui/theme.css'), 'utf8');
const body = '<div id="root"></div>';
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>${css}</style><!-- Open source notices:\n${notices.replace(/--/g, '—')} --></head><body>${body}<script type="application/json" id="umeda-reader-code">${JSON.stringify(readerJs).replace(/</g, '\\u003c')}</script><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
await fs.mkdir(path.join(root, 'dist'), { recursive: true });
await fs.writeFile(path.join(root, 'dist/workbench.js'), js);
await fs.writeFile(path.join(root, 'dist/reader.js'), readerJs);
await fs.writeFile(path.join(root, 'dist/THIRD_PARTY_NOTICES.txt'), notices);
await fs.writeFile(path.join(root, 'dist/theme.css'), css);
await fs.writeFile(path.join(root, 'dist/index.html'), `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="theme.css"></head><body>${body}<script src="workbench.js"></script></body></html>`);
await build({ entryPoints: [path.join(root, 'src/library/plugin.ts')], outfile: path.join(root, 'dist/plugin-main.js'), bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true, legalComments: 'inline' });
const mobile = path.join(root, 'generated/mobile.ts');
await fs.mkdir(path.dirname(mobile), { recursive: true });
const generated = `// Generated by packages/kos-workbench/build.mjs. Contains no user data or endpoints.\nexport const KOS_WORKBENCH_HTML: string = ${JSON.stringify(html)};\n`;
if (await fs.readFile(mobile, 'utf8').catch(() => '') !== generated) await fs.writeFile(mobile, generated);
console.log(`Built KOS startup (${Math.round(js.length / 1024)} KiB), deferred readers (${Math.round(readerJs.length / 1024)} KiB), plugin assets and mobile embedded view.`);
